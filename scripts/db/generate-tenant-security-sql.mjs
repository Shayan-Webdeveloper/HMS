// Generates the database-level tenant isolation SQL (RLS policies, grants and cross-hospital
// reference guards) from the Prisma data model, so the SQL can never drift from the schema.
//
//   node scripts/db/generate-tenant-security-sql.mjs > prisma/migrations/<timestamp>_<name>/migration.sql
//
// Re-run it (into a NEW migration) whenever a hospital-owned model or relation is added.
// tests/unit/tenancy-model.test.js fails if the latest generated migration is out of date.
import { tenantModels, GLOBAL_MODELS } from "../../lib/db/tenancy-model.js";
import { readSchemaRelations } from "./schema-relations.mjs";

/** Relations between two hospital-owned models (excluding the Hospital relation itself). */
export function tenantRelations() {
  const tenants = new Set(tenantModels());
  return readSchemaRelations().filter((r) => tenants.has(r.model) && tenants.has(r.target) && r.column !== "hospitalId");
}

const q = (s) => `"${s}"`;
const CTX = "(SELECT hms_internal.current_hospital_id())";

// Append-only for the application role: rows can be added and read, never changed or removed.
const APPEND_ONLY = new Set(["AuditLog"]);

export function generateTenantSecuritySql() {
  const models = tenantModels();
  const relations = tenantRelations();
  const out = [];
  const p = (s = "") => out.push(s);

  p(`-- GENERATED by scripts/db/generate-tenant-security-sql.mjs — do not edit by hand.
--
-- Database-level hospital isolation (defence in depth under the application's own checks).
--
-- How it works
--   * The application connects as the owner role (Supabase "postgres", which has BYPASSRLS), but
--     every hospital-scoped query runs inside a transaction that first executes
--         SELECT set_config('role', 'hms_app', true), set_config('app.hospital_id', <id>, true)
--     Both settings are TRANSACTION-LOCAL: they end at COMMIT/ROLLBACK, so a pooled connection can
--     never carry one request's hospital into the next request.
--   * hms_app has no BYPASSRLS. The policies below only expose rows whose "hospitalId" equals the
--     transaction's hospital, and WITH CHECK makes it impossible to write a row for another hospital.
--   * Without app.hospital_id, hms_app sees nothing and cannot insert (the column default is NULL).
--   * BEFORE triggers reject (a) references from one hospital's row to another hospital's row and
--     (b) moving an existing row to a different hospital — even for the owner role.
--   * anon / authenticated (Supabase Data API) get no policies at all; their grants are revoked in
--     a separate migration.`);
  p();
  p(`-- ── Internal helpers (not in an API-exposed schema) ───────────────────────────
CREATE SCHEMA IF NOT EXISTS hms_internal;
REVOKE ALL ON SCHEMA hms_internal FROM PUBLIC;

CREATE OR REPLACE FUNCTION hms_internal.current_hospital_id() RETURNS text
LANGUAGE sql STABLE PARALLEL SAFE
AS $$ SELECT NULLIF(current_setting('app.hospital_id', true), '') $$;

-- Rejects cross-hospital references and hospital reassignment. SECURITY DEFINER so it can see the
-- referenced row even when RLS would hide it from the caller (that is exactly the case to reject).
CREATE OR REPLACE FUNCTION hms_internal.enforce_same_hospital() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog
AS $$
DECLARE
  i int;
  col text;
  parent text;
  ref_id text;
  parent_hospital text;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW."hospitalId" IS DISTINCT FROM OLD."hospitalId" THEN
    RAISE EXCEPTION 'HMS_TENANT_VIOLATION: rows of % cannot be moved to another hospital', TG_TABLE_NAME
      USING ERRCODE = 'check_violation';
  END IF;
  IF TG_NARGS = 0 THEN
    RETURN NEW;
  END IF;
  FOR i IN 0 .. (TG_NARGS / 2) - 1 LOOP
    col := TG_ARGV[i * 2];
    parent := TG_ARGV[i * 2 + 1];
    ref_id := to_jsonb(NEW) ->> col;
    CONTINUE WHEN ref_id IS NULL;
    parent_hospital := NULL;
    EXECUTE format('SELECT "hospitalId" FROM public.%I WHERE id = $1', parent) INTO parent_hospital USING ref_id;
    -- (EXECUTE … INTO does not set FOUND.) A missing parent is reported by the foreign key itself.
    IF parent_hospital IS NOT NULL AND parent_hospital IS DISTINCT FROM NEW."hospitalId" THEN
      RAISE EXCEPTION 'HMS_TENANT_VIOLATION: %.% references a % row that belongs to another hospital', TG_TABLE_NAME, col, parent
        USING ERRCODE = 'check_violation';
    END IF;
  END LOOP;
  RETURN NEW;
END;
$$;
-- True when an account belongs to NO hospital at all. SECURITY DEFINER: it must see memberships of
-- every hospital (under RLS a member of another hospital would wrongly look unattached).
CREATE OR REPLACE FUNCTION hms_internal.is_unattached_user(uid text) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog
AS $$ SELECT NOT EXISTS (SELECT 1 FROM public."HospitalMembership" m WHERE m."userId" = uid) $$;
REVOKE ALL ON FUNCTION hms_internal.current_hospital_id() FROM PUBLIC;
REVOKE ALL ON FUNCTION hms_internal.enforce_same_hospital() FROM PUBLIC;
REVOKE ALL ON FUNCTION hms_internal.is_unattached_user(text) FROM PUBLIC;`);
  p();
  p(`-- ── Restricted application role ────────────────────────────────────────────────
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'hms_app') THEN
    CREATE ROLE hms_app NOLOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOINHERIT;
  END IF;
END $$;
-- The connecting role must be able to switch into hms_app for a transaction.
GRANT hms_app TO CURRENT_USER;
GRANT USAGE ON SCHEMA public TO hms_app;
GRANT USAGE ON SCHEMA hms_internal TO hms_app;
GRANT EXECUTE ON FUNCTION hms_internal.current_hospital_id() TO hms_app;
GRANT EXECUTE ON FUNCTION hms_internal.is_unattached_user(text) TO hms_app;`);
  p();

  p(`-- ── Global tables ──────────────────────────────────────────────────────────────`);
  p(`-- Hospital: a hospital context can read and update only its own row.
ALTER TABLE "Hospital" ENABLE ROW LEVEL SECURITY;
GRANT SELECT, UPDATE ON "Hospital" TO hms_app;
DROP POLICY IF EXISTS hms_own_hospital ON "Hospital";
CREATE POLICY hms_own_hospital ON "Hospital" FOR ALL TO hms_app
  USING ("id" = ${CTX}) WITH CHECK ("id" = ${CTX});

-- Role / Permission: global catalogue (names only, no hospital data). Read-only for the app.
ALTER TABLE "Role" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "Permission" ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON "Role", "Permission" TO hms_app;
DROP POLICY IF EXISTS hms_catalogue_read ON "Role";
CREATE POLICY hms_catalogue_read ON "Role" FOR SELECT TO hms_app USING (true);
DROP POLICY IF EXISTS hms_catalogue_read ON "Permission";
CREATE POLICY hms_catalogue_read ON "Permission" FOR SELECT TO hms_app USING (true);

-- User: visible/updatable only for members of the current hospital. An account with NO membership at
-- all (a brand-new account, for the moment between its INSERT … RETURNING and the insert of its
-- membership) is also visible; platform accounts never are. Members of other hospitals are invisible.
ALTER TABLE "User" ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE ON "User" TO hms_app;
DROP POLICY IF EXISTS hms_user_select ON "User";
CREATE POLICY hms_user_select ON "User" FOR SELECT TO hms_app USING (
  EXISTS (SELECT 1 FROM "HospitalMembership" m WHERE m."userId" = "User"."id" AND m."hospitalId" = ${CTX})
  OR ("User"."platformRole" IS NULL AND hms_internal.is_unattached_user("User"."id"))
);
DROP POLICY IF EXISTS hms_user_insert ON "User";
CREATE POLICY hms_user_insert ON "User" FOR INSERT TO hms_app WITH CHECK (${CTX} IS NOT NULL AND "platformRole" IS NULL);
DROP POLICY IF EXISTS hms_user_update ON "User";
CREATE POLICY hms_user_update ON "User" FOR UPDATE TO hms_app USING (
  EXISTS (SELECT 1 FROM "HospitalMembership" m WHERE m."userId" = "User"."id" AND m."hospitalId" = ${CTX})
  OR ("User"."platformRole" IS NULL AND hms_internal.is_unattached_user("User"."id"))
) WITH CHECK ("platformRole" IS NULL);

-- Session: hospital staff may only list/revoke sessions of their own hospital's members.
ALTER TABLE "Session" ENABLE ROW LEVEL SECURITY;
GRANT SELECT, DELETE ON "Session" TO hms_app;
DROP POLICY IF EXISTS hms_session_members ON "Session";
CREATE POLICY hms_session_members ON "Session" FOR ALL TO hms_app USING (
  EXISTS (SELECT 1 FROM "HospitalMembership" m WHERE m."userId" = "Session"."userId" AND m."hospitalId" = ${CTX})
);

-- PasswordResetToken, RateLimitBucket, _prisma_migrations: no access for hms_app (auth layer only).
ALTER TABLE "PasswordResetToken" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "RateLimitBucket" ENABLE ROW LEVEL SECURITY;`);
  p();

  p(`-- ── Hospital-owned tables (${models.length}) ─────────────────────────────────────────────`);
  for (const m of models) {
    const t = q(m);
    p(`ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`);
    p(`DROP POLICY IF EXISTS hms_tenant_isolation ON ${t};`);
    if (APPEND_ONLY.has(m)) {
      p(`GRANT SELECT, INSERT ON ${t} TO hms_app;`);
      p(`CREATE POLICY hms_tenant_isolation ON ${t} FOR SELECT TO hms_app USING ("hospitalId" = ${CTX});`);
      p(`DROP POLICY IF EXISTS hms_tenant_insert ON ${t};`);
      p(`CREATE POLICY hms_tenant_insert ON ${t} FOR INSERT TO hms_app WITH CHECK ("hospitalId" = ${CTX});`);
    } else {
      p(`GRANT SELECT, INSERT, UPDATE, DELETE ON ${t} TO hms_app;`);
      p(`CREATE POLICY hms_tenant_isolation ON ${t} FOR ALL TO hms_app USING ("hospitalId" = ${CTX}) WITH CHECK ("hospitalId" = ${CTX});`);
    }
    const rels = relations.filter((r) => r.model === m);
    const args = rels.flatMap((r) => [`'${r.column}'`, `'${r.target}'`]).join(", ");
    const cols = ['"hospitalId"', ...rels.map((r) => q(r.column))].join(", ");
    p(`DROP TRIGGER IF EXISTS hms_same_hospital ON ${t};`);
    p(`CREATE TRIGGER hms_same_hospital BEFORE INSERT OR UPDATE OF ${cols} ON ${t} FOR EACH ROW EXECUTE FUNCTION hms_internal.enforce_same_hospital(${args});`);
    p();
  }
  p(`-- Global models (no hospitalId): ${GLOBAL_MODELS.join(", ")}`);
  return out.join("\n") + "\n";
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, "/")}` || process.argv[1]?.endsWith("generate-tenant-security-sql.mjs")) {
  process.stdout.write(generateTenantSecuritySql());
}
